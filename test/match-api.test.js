'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { createMatchStore } = require('../lib/match-store');
const { installMatchRoutes } = require('../lib/match-routes');
const { fixture } = require('./fixtures');

test('HTTP contract preserves GET shape and acknowledges committed writes with revision', async t => {
  let fail = false;
  const store = createMatchStore({ initial: fixture(), persist: async () => { if (fail) throw Error('test disk failure'); } });
  const app = express(); app.use(express.json()); installMatchRoutes(app, () => store);
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}/api/matchdata`;
  const initial = await fetch(url);
  assert.deepEqual(await initial.json(), fixture());
  assert.equal(initial.headers.get('cache-control'), 'no-store');
  const revision = initial.headers.get('x-match-revision');
  const change = { path: ['game_duration'], previous: { exists: true, value: '00:00' }, value: '02:00' };
  const patch = changes => fetch(url, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ changes }) });
  const saved = await patch([change]);
  assert.equal(saved.status, 200);
  const result = await saved.json();
  assert.equal(result.data.game_duration, '02:00');
  assert.notEqual(result.revision, revision);
  assert.equal(saved.headers.get('etag'), result.revision);
  const conflict = await patch([change]);
  assert.equal(conflict.status, 409);
  assert.deepEqual((await conflict.json()).conflicts, [['game_duration']]);
  const stalePost = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json', 'If-Match': revision }, body: JSON.stringify(fixture()) });
  assert.equal(stalePost.status, 409);
  const partial = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(partial.status, 400);
  fail = true;
  assert.equal((await patch([{ ...change, previous: { exists: true, value: '02:00' }, value: '03:00' }])).status, 503);
  assert.equal((await (await fetch(url)).json()).game_duration, '02:00');
});
